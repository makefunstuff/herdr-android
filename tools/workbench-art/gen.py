# Turns the Herdr desktop's workbench art (personal-herdr-desktop/herdr-app: workbench-icons, mods/px-chrome/gw,
# backgrounds/workbench.svg; Apache 2.0) into app/src/main/kotlin/.../ui/design/WorkbenchArt.kt.
# python3 tools/workbench-art/gen.py app/src/main/kotlin/com/makefunstuff/herdr/ui/design/WorkbenchArt.kt [herdr-app folder]
import re, sys, os, glob
SRC = sys.argv[2] if len(sys.argv) > 2 else "/data/jpl/Work/personal-herdr-desktop/herdr-app"
OUT = sys.argv[1]
rect = re.compile(r'<rect([^>]*)/>')
attr = lambda s, n: (re.search(r'\b%s="([^"]*)"' % n, s) or [None, None])[1]

def fmt(v):
    v = round(float(v), 3)
    return ("%g" % v)

def rects(svg):
    out = []
    for m in rect.finditer(svg):
        a = m.group(1)
        out.append((attr(a, "x") or "0", attr(a, "y") or "0", attr(a, "width"), attr(a, "height"), attr(a, "fill")))
    return out

def path(rs):
    return "".join("M%s %sh%sv%sh-%sz" % (fmt(x), fmt(y), fmt(w), fmt(h), fmt(w)) for x, y, w, h, _ in rs)

def camel(n):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r'[-_]', n))

lines = []
lines.append("""package com.makefunstuff.herdr.ui.design

import androidx.compose.ui.graphics.vector.ImageVector

/*
 * Generated by tools/workbench-art/gen.py from the Herdr desktop's workbench art
 * (personal-herdr-desktop, herdr-app/: the workbench-icons and mods/px-chrome/gw folders and
 * backgrounds/workbench.svg; Apache 2.0). Pixel rectangles as path data. Don't edit by hand.
 */
""")
# Dot-matrix glyphs: one path each, drawn in the icon's tint.
lines.append("/** The workbench's dot-matrix glyphs (px-chrome/gw), on their 14-unit grid from -1. */")
lines.append("internal object GlyphArt {")
for f in sorted(glob.glob(SRC + "/mods/px-chrome/gw/*.svg")):
    n = os.path.basename(f)[:-4]
    svg = open(f).read()
    if 'viewBox="-1 -1 14 14"' not in svg:
        print("skip", n, file=sys.stderr); continue
    lines.append('    val %s: ImageVector by lazy { glyph("%s", "%s") }' % (camel(n), camel(n), path(rects(svg))))
lines.append("}\n")
# Chip-package icons: body, pins and ink, each drawn in a theme colour.
ink = {"#ffb000": "Agent", "#4fd1c5": "Runtime", "#8fa3a8": "Tool"}
lines.append("/** The workbench's chip-package program icons (workbench-icons), on a 24-unit grid: body, pins, ink. */")
lines.append("internal object ChipArt {")
files = sorted(glob.glob(SRC + "/workbench-icons/*.svg")) + [SRC + "/mods/px-chrome/herdr-wb-chip.svg"]
for f in files:
    n = os.path.basename(f)[:-4]
    if n == "herdr-wb-chip": n = "herdr"
    rs = rects(open(f).read())
    frame = rs[0]; body = [r for r in rs if r[4] == "#15181a"]; pins = [r for r in rs if r[4] == "#66727a"]
    inks = [r for r in rs[1:] if r[4] not in ("#15181a", "#66727a")]
    family = ink.get(frame[4], "Tool")
    if n == "herdr":
        # The brand chip: grey frame, amber logic, a teal and grey detail; drawn as agent ink.
        family = "Agent"
    lines.append('    val %s by lazy { Chip(ChipInk.%s, frameData = "%s", bodyData = "%s", pinsData = "%s", markData = "%s") }' % (camel(n), family, path([frame]), path(body), path(pins), path(inks)))
lines.append("}\n")
# The circuit board, by colour.
rs = rects(open(SRC + "/backgrounds/workbench.svg").read())
roles = {"#122019": "trace", "#24382d": "bus", "#1d2f25": "pad", "#0b120e": "hole", "#4a4026": "part"}
lines.append("/** The workbench's circuit board (backgrounds/workbench.svg, 1920 x 1200), one path per layer. */")
lines.append("internal object CircuitArt {")
lines.append("    const val WIDTH = 1920f\n    const val HEIGHT = 1200f")
for col, role in roles.items():
    sel = [r for r in rs if r[4] == col and not (r[2] == "1920" and r[3] == "1200")]
    lines.append('    val %s = "%s"' % (role, path(sel)))
lines.append("}")
open(OUT, "w").write("\n".join(lines) + "\n")
